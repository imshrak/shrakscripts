return function(Library)
    local window
    local ok, message = xpcall(function()
        window = Library:CreateWindow({ Id = "ShrakUISmoke", Title = "UI tests", DeferShow = true, AutoShow = false, UnlockMouse = false, ConfigFolder = "ShrakScripts/UITests" })
        local tab = window:AddTab("Controls", "settings")
        local group = tab:AddGroupbox("Controls")
        local changes = 0
        local toggle = group:AddToggle("Enabled", { Tooltip = "Enable", Callback = function() changes += 1 end })
        local slider = group:AddSlider("Amount", { Min = 0, Max = 10, Default = 2.5, Rounding = 1 })
        local input = group:AddInput("Name", { Default = "Test", MaxLength = 12 })
        local numeric = group:AddInput("Number", { Numeric = true, Default = 12 })
        local picker = group:AddColorPicker("Color", { Default = Color3.fromRGB(255, 80, 30), Transparency = 0.25 })
        local key = group:AddKeybind("Key", { Default = "F", Mode = "Hold" })
        local drop = group:AddDropdown("Mode", { Values = { "One", "Two" }, Default = "One" })
        local multi = group:AddDropdown("Items", { Multi = true, Values = { "A", "B" }, Default = { "A" } })
        input:SetDependency(toggle, true)
        tab:AddLabel("Label"):SetText("Updated")
        local presses = 0
        tab:AddButton("Button", function() presses += 1 end):Press()
        assert(presses == 1)
        tab:AddDivider("Divider")
        local box = tab:AddTabbox("Advanced")
        local first = box:AddTab("First")
        local second = box:AddTab("Second")
        first:AddLabel("First page")
        second:AddSlider("Nested", { Min = 0, Max = 1, Default = 0.5, Rounding = 2 })
        box:SelectTab("Second")
        assert(second.Page.Visible and not first.Page.Visible)
        window:Ready()
        task.wait(0.2)
        assert(not input.Frame.Visible)
        toggle:SetValue(true, true)
        assert(changes == 0 and input.Frame.Visible)
        toggle:SetValue(false)
        toggle:SetValue(true)
        assert(changes == 2)
        if getconnections then
            local hitbox = toggle.Frame:FindFirstChildWhichIsA("TextButton")
            for _, connection in ipairs(getconnections(hitbox.Activated)) do if connection.Function then connection.Function() end end
            assert(not toggle.Value and not input.Frame.Visible)
            toggle:SetValue(true)
        end
        slider:SetValue(7.26, true)
        assert(slider.Value == 7.3)
        assert(numeric:SetValue("invalid") == false)
        input:SetValue("abcdefghijklmnop")
        assert(input.Value == "abcdefghijkl")
        picker:SetValueRGB(Color3.fromRGB(10, 20, 30), 0.5)
        local chosen = picker.Value
        window:SetTheme("Nord")
        assert(picker.Value == chosen and picker.Frame.BackgroundColor3 == window.Theme.Surface)
        local swatch = picker.Frame:FindFirstChild("Swatch")
        assert(swatch.BackgroundColor3 == chosen)
        window:SetTheme({ Accent = Color3.new(1, 1, 1), Text = Color3.new(1, 1, 1) })
        window:SetTheme({ Accent = Color3.fromRGB(255, 0, 80) })
        assert(swatch.BackgroundColor3 == chosen)
        local square = picker.Frame:FindFirstChild("SaturationValue", true)
        assert(square.BackgroundColor3 ~= window.Theme.Accent)
        window:SetSize(620, 480)
        window:SetTitle("Updated", "Subtitle")
        window:SetTextScale(1.1)
        window:SetFont("rbxasset://fonts/families/GothamSSm.json")
        local added = tab:AddInput("Later", { Default = "After customization" })
        assert(added.TextBox.TextSize == 15)
        local json = window:ExportConfig()
        toggle:SetValue(false)
        slider:SetValue(0)
        picker:SetValue(Color3.new())
        assert(window:ImportConfig(json))
        assert(toggle.Value and slider.Value == 7.3 and picker.Value == chosen and picker.Transparency == 0.5)
        assert(input.Frame.Visible and key.Mode == "Hold")
        local invalid = window:GetConfig()
        invalid.Controls.Amount.Value = "invalid"
        assert(not window:ImportConfig(invalid))
        assert(toggle.Value and slider.Value == 7.3)
        invalid = window:GetConfig()
        invalid.Controls.Name.Value = "changed"
        invalid.Controls.Mode.Value = "Missing"
        assert(not window:ImportConfig(invalid))
        assert(input.Value == "abcdefghijkl" and drop.Value == "One")
        drop:SetValues({ "Two", "Three" })
        assert(drop.Value == "Two")
        multi:SetValue({ B = true })
        assert(multi.Value.B and not multi.Value.A)
        key:SetMode("Always")
        assert(key:GetState())
        key:SetMode("Toggle")
        assert(not key:GetState())
        input:SetDisabled(true)
        assert(input.Disabled and input.Frame:FindFirstChild("DisabledOverlay").Visible)
        input:SetDisabled(false)
        group:SetCollapsed(true)
        assert(not group.Page.Visible)
        group:SetCollapsed(false)
        local settings = window:AddTab("Settings", "settings")
        window:AddThemeSection(settings)
        window:AddConfigSection(settings)
        local notice = window:Notify({ Title = "Tests", Text = "Passed", Duration = 0 })
        notice:SetText("Updated"):Close()
        assert(not notice.Frame)
        if writefile and readfile and makefolder and isfolder and listfiles and delfile then
            local profile = "Smoke_" .. game:GetService("HttpService"):GenerateGUID(false)
            local saved, reason = window:SaveConfig(profile)
            assert(saved, reason)
            assert(table.find(window:ListConfigs(), profile))
            local loaded, loadReason = window:LoadConfig(profile)
            assert(loaded, loadReason)
            assert(window:DeleteConfig(profile))
        end
        window:StopAll()
        assert(not toggle.Value)
        print("SHRAK_UI_SMOKE_PASSED", Library.Version, #json, group.Frame.AbsoluteSize.Y)
    end, debug.traceback)
    if window then window:Unload() end
    assert(ok, message)
    local mobile = Library:CreateWindow({ Id = "ShrakUIMobileSmoke", Mobile = true, Width = 360, Height = 520, AutoShow = true, UnlockMouse = false, DeferShow = true })
    local mobileOk, mobileError = xpcall(function()
        local tab = mobile:AddTab("Mobile")
        local group = tab:AddGroupbox("Touch controls")
        local input = group:AddInput("MobileInput", { Default = "Touch" })
        group:AddColorPicker("MobileColor", { Default = Color3.fromRGB(120, 180, 255) })
        group:AddKeybind("MobileKey", { Default = "F" })
        group:AddDropdown("MobileChoice", { Values = { "One", "Two" } })
        mobile:Ready()
        mobile.Screen.Enabled = false
        task.wait(0.15)
        assert(mobile.Frame.AbsoluteSize.X == 360 and mobile.Frame.AbsoluteSize.Y == 520)
        assert(input.Frame.AbsoluteSize.X > 120 and input.TextBox.AbsoluteSize.Y >= 36)
        assert(group.Page.AbsoluteSize.Y > 0)
        print("SHRAK_UI_MOBILE_PASSED", mobile.Frame.AbsoluteSize, input.Frame.AbsoluteSize)
    end, debug.traceback)
    mobile:Unload()
    assert(mobileOk, mobileError)
    return true
end
